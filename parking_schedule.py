"""Version-controlled release policy shared by the worker and timer generator."""

from dataclasses import dataclass
from datetime import date, datetime, time, timedelta, timezone
from zoneinfo import ZoneInfo

from parking_booking import MADRID

ZONE = ZoneInfo(MADRID)
DAY_NAMES = ("Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun")
WARMUP = timedelta(seconds=60)
LATE_START = timedelta(seconds=60)


@dataclass(frozen=True)
class Occurrence:
    release: datetime  # UTC, so elapsed time never depends on a DST fold

    @property
    def wake(self):
        return self.release - WARMUP

    @property
    def close(self):
        return self.release + LATE_START

    @property
    def target(self):
        return self.release.astimezone(ZONE).date() + timedelta(days=7)


@dataclass(frozen=True)
class Schedule:
    release_time: time | None
    parking_weekdays: tuple[int, ...]  # Monday=0, Sunday=6
    building: str | None
    floor: str | None

    @property
    def enabled(self):
        return bool(self.release_time is not None and self.parking_weekdays and self.building and self.floor)

    def __post_init__(self):
        if self.release_time and (self.release_time.tzinfo or self.release_time.microsecond):
            raise ValueError("Use a Madrid wall time at whole-second precision")
        if any(day not in range(7) for day in self.parking_weekdays):
            raise ValueError("Use weekday numbers from 0 (Monday) through 6 (Sunday)")

    def occurrence(self, release_day):
        if self.release_time is None or release_day.weekday() not in self.parking_weekdays:
            return None
        local = datetime.combine(release_day, self.release_time, ZONE).replace(fold=0)
        release = local.astimezone(timezone.utc)
        # A skipped wall time has no release. At a repeated wall time use fold 0.
        if release.astimezone(ZONE) != local:
            return None
        return Occurrence(release)

    def active(self, now):
        local_day = now.astimezone(ZONE).date()
        for delta in (-1, 0, 1):
            occurrence = self.occurrence(local_day + timedelta(days=delta))
            if occurrence and occurrence.wake <= now < occurrence.close:
                return occurrence
        return None

    def calendars(self):
        if self.release_time is None or not self.parking_weekdays:
            return []
        reference = datetime.combine(date(2000, 1, 3), self.release_time)
        wake = reference - WARMUP
        day_delta = (wake.date() - reference.date()).days
        weekdays = sorted({(day + day_delta) % 7 for day in self.parking_weekdays})
        names = ",".join(DAY_NAMES[day] for day in weekdays)
        calendars = [f"{names} *-*-* {wake:%H:%M:%S} {MADRID}"]
        if 6 in self.parking_weekdays and day_delta == 0 and wake.time() < time(3) <= reference.time():
            # The ordinary wall wake is skipped in March and occurs one hour too
            # early in October. Add the elapsed-time wake on Madrid's transition Sundays.
            calendars.extend(f"Sun *-{month}~01..07 {wake - timedelta(hours=offset):%H:%M:%S} UTC"
                             for month, offset in (("03", 2), ("10", 1)))
        return calendars


