def render_timer(schedule):
    if not schedule.enabled:
        raise ValueError("Set the release time, parking weekdays, building and floor before rendering the timer")
    return "\n".join([
        "# Generated by parking_release.py timer from parking_schedule.py.",
        "[Unit]",
        "Description=Wake before Bookker parking release",
        "",
        "[Timer]",
        *(f"OnCalendar={calendar}" for calendar in schedule.calendars()),
        "AccuracySec=1us",
        "RandomizedDelaySec=0",
        "Persistent=false",
        "Unit=bookker-parking.service",
        "",
        "[Install]",
        "WantedBy=timers.target",
        "",
    ])
